let seq = 0;
// Timestamped, like post ids. A bare counter restarts every process, so the
// first comment added after a reload would be c-1 again and collide with a
// seed row — React then warns about the duplicate key and hideComment hides
// whichever one it finds first.
export const nextId = (prefix: string) =>
  `${prefix}-${Date.now().toString(36)}-${++seq}`;

// Fixed base date so server and client render identical markup.
const BASE = Date.UTC(2026, 9, 10, 9, 0, 0);
export const ago = (days: number, hour = 9) => {
  const d = new Date(BASE - days * 86_400_000);
  d.setUTCHours(hour, 0, 0, 0);
  return d.toISOString();
};

